#!/usr/bin/env python3
"""Independent-process relay proof in private, caller-owned Linux namespaces.

Run as a non-root caller; never pass the internal --inside switch:
    python3 test/relay_endpoint_smoke.py --rust-peer "$RUST_PEER" \\
        --zig-peer "$ZIG_PEER" \\
        --mode nat --zig-role server --qad-cert "$QAD_CERT" --qad-key "$QAD_KEY"

Repeat with --zig-role client for the opposite direction. Relay-only mode
uses --mode relay-only and needs no QAD options. QAD_CERT must be an
externally supplied DER certificate with IP SANs 10.231.1.1 and 10.231.2.1;
QAD_KEY must be its externally supplied PKCS#8 DER key. Only the relay server
receives the private key; only Rust uses QAD. Zig's 10.231.1.2:4444 candidate
is explicitly configured, not observed through QAD. No certificate or key is
generated by this driver. If conntrack is installed, both routers' actual
direct UDP masquerade mappings are logged and must preserve source port 4444.
Carrier mode uses --mode carrier without QAD options and launches exactly two
role processes. It verifies pinned relay carrier identities and exact payloads,
not an inner authenticated endpoint connection. Exercise both --zig-role values.
The default Alice/Bob identity pins match the fixed 5a/6c test seeds.
Override --alice-id or --bob-id only to exercise pin rejection.

The outer driver snapshots its own net/user namespace IDs and non-root UID
before unshare. Its --inside child consumes the reserved
_OZAI_RELAY_SMOKE_OUTER_NET_NS, _OZAI_RELAY_SMOKE_OUTER_USER_NS, and
_OZAI_RELAY_SMOKE_OUTER_UID environment metadata before any network setup.
These are internal handoff values, not user options; inherited values are
overwritten by the outer driver, and a missing or malformed handoff is fatal.
Namespace safety regressions run without namespace or network operations:
    python3 -m unittest discover -s test -p relay_endpoint_smoke.py
"""
import argparse
import os
import re
import selectors
import shutil
import subprocess
import sys
import time
import unittest

PHASE = re.compile(r"relay-phase([12]): stable_id (\d+) remote_id ([0-9a-f]{64}) selected (relay|direct) bytes (\d+).*payload_hex ([0-9a-f]+)")
CARRIER = re.compile(r"relay-carrier: remote_id ([0-9a-f]{64}) payload_hex ([0-9a-f]+)")

OUTER_NAMESPACE_ENV = {
    "net": "_OZAI_RELAY_SMOKE_OUTER_NET_NS",
    "user": "_OZAI_RELAY_SMOKE_OUTER_USER_NS",
    "uid": "_OZAI_RELAY_SMOKE_OUTER_UID",
}


def validate_namespace_metadata(baseline, current, uid, euid, uid_map_text):
    """Fail closed using caller snapshots and actual inner kernel metadata."""
    for namespace in ("net", "user"):
        expected = baseline.get(namespace)
        if not isinstance(expected, str) or not re.fullmatch(
                rf"{namespace}:\[[1-9][0-9]*\]", expected):
            raise RuntimeError("requires a complete, valid outer namespace baseline")
    outer_uid = baseline.get("uid")
    if not isinstance(outer_uid, str) or not re.fullmatch(r"[1-9][0-9]*", outer_uid):
        raise RuntimeError("requires a complete, valid non-root outer namespace baseline")
    for namespace in ("net", "user"):
        actual = current.get(namespace)
        if not isinstance(actual, str) or not re.fullmatch(
                rf"{namespace}:\[[1-9][0-9]*\]", actual):
            raise RuntimeError(f"invalid current {namespace} namespace metadata")
        if actual == baseline[namespace]:
            raise RuntimeError(f"refusing to run in the caller's {namespace} namespace")
    try:
        uid_map = [tuple(map(int, line.split())) for line in uid_map_text.splitlines()]
    except ValueError as error:
        raise RuntimeError("requires a private user namespace with a valid UID mapping") from error
    if uid != 0 or euid != 0 or uid_map != [(0, int(outer_uid), 1)]:
        raise RuntimeError("requires a private user namespace mapping the non-root caller to root")



def command(*args, input=None):
    return subprocess.run(args, input=input, text=True, check=True, stdout=subprocess.PIPE).stdout


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--rust-peer", required=True)
    parser.add_argument("--zig-peer", required=True)
    parser.add_argument("--alice-id",
        default="0d7550754e0800a5d237eef5826035766b9b3e5a15868a940ab289958788e3b0")
    parser.add_argument("--bob-id",
        default="6d44f939f829d43598bcdedda90de01db69faa50caa33e8c6c328a4b900d4dac")
    parser.add_argument("--mode", choices=("relay-only", "nat", "carrier"), default="relay-only")
    parser.add_argument("--zig-role", choices=("server", "client"), default="server")
    parser.add_argument("--message", default="ozai-relay-exact-application-bytes")
    parser.add_argument("--timeout", type=int, default=60)
    parser.add_argument("--qad-cert", help="externally supplied DER certificate (required for nat)")
    parser.add_argument("--qad-key", help="externally supplied PKCS#8 DER key (required for nat)")
    parser.add_argument("--inside", action="store_true", help=argparse.SUPPRESS)
    args = parser.parse_args()
    for identity in (args.alice_id, args.bob_id):
        if not re.fullmatch(r"[0-9a-f]{64}", identity):
            parser.error("identities must be lowercase Ed25519 public-key hex")
    if args.mode == "nat" and (not args.qad_cert or not args.qad_key):
        parser.error("nat mode requires --qad-cert and --qad-key")
    if not args.inside:
        outer_uid = os.getuid()
        if outer_uid == 0 or os.geteuid() == 0:
            raise RuntimeError("requires a non-root outer caller")
        # Read only caller-owned handles; PID 1 can be inaccessible after unshare.
        baseline = {namespace: os.readlink(f"/proc/self/ns/{namespace}")
                    for namespace in ("net", "user")}
        baseline["uid"] = str(outer_uid)
        child_env = os.environ.copy()
        child_env.update({name: baseline[key] for key, name in OUTER_NAMESPACE_ENV.items()})
        argv = ["unshare", "--user", "--map-root-user", "--net", sys.executable,
                os.path.abspath(__file__), *sys.argv[1:], "--inside"]
        return subprocess.call(argv, env=child_env)
    # Consume the handoff so spawned peers do not inherit private safety metadata.
    baseline = {key: os.environ.pop(name, None) for key, name in OUTER_NAMESPACE_ENV.items()}
    current = {namespace: os.readlink(f"/proc/self/ns/{namespace}")
               for namespace in ("net", "user")}
    with open("/proc/self/uid_map", encoding="ascii") as mapping:
        uid_map_text = mapping.read()
    validate_namespace_metadata(baseline, current, os.getuid(), os.geteuid(), uid_map_text)
    children = []
    selector = selectors.DefaultSelector()
    buffers = {}
    output_bytes = {}
    closed = set()
    try:
        command("ip", "link", "set", "lo", "up")
        spaces = {}
        # Every namespace keeper is a direct child; namespace handles are its PID,
        # never a host-global /run/netns name.
        for name in ("alice", "bob", "router-a", "router-b"):
            child = subprocess.Popen(["unshare", "--net", "sleep", str(args.timeout + 20)])
            children.append(child)
            spaces[name] = child.pid
            for _ in range(100):
                if child.poll() is not None:
                    raise RuntimeError("namespace keeper exited")
                if os.readlink(f"/proc/{child.pid}/ns/net") != os.readlink("/proc/self/ns/net"):
                    break
                time.sleep(.01)
            else:
                raise TimeoutError("namespace creation")
            command("nsenter", "-t", str(child.pid), "-n", "ip", "link", "set", "lo", "up")

        def net(name, *argv, input=None):
            return command("nsenter", "-t", str(spaces[name]), "-n", *argv, input=input)

        for index, (peer, router) in enumerate((("alice", "router-a"), ("bob", "router-b")), 1):
            wan = f"wan{index}"
            command("ip", "link", "add", wan, "type", "veth", "peer", "name", "uplink")
            command("ip", "link", "set", "uplink", "netns", str(spaces[router]))
            command("ip", "addr", "add", f"10.231.{index}.1/24", "dev", wan)
            command("ip", "link", "set", wan, "up")
            net(router, "ip", "addr", "add", f"10.231.{index}.2/24", "dev", "uplink")
            net(router, "ip", "link", "set", "uplink", "up")
            net(router, "ip", "route", "add", "default", "via", f"10.231.{index}.1")
            command("ip", "link", "add", f"lan{index}", "type", "veth", "peer", "name", f"endpoint{index}")
            command("ip", "link", "set", f"lan{index}", "netns", str(spaces[router]))
            command("ip", "link", "set", f"endpoint{index}", "netns", str(spaces[peer]))
            net(router, "ip", "addr", "add", f"10.232.{index}.1/24", "dev", f"lan{index}")
            net(router, "ip", "link", "set", f"lan{index}", "up")
            net(peer, "ip", "addr", "add", f"10.232.{index}.2/24", "dev", f"endpoint{index}")
            net(peer, "ip", "link", "set", f"endpoint{index}", "up")
            net(peer, "ip", "route", "add", "default", "via", f"10.232.{index}.1")
            net(router, "sysctl", "-q", "-w", "net.ipv4.ip_forward=1")
            rules = f"""table ip relay_smoke {{
 chain nat {{ type nat hook postrouting priority srcnat; oifname \"uplink\" masquerade; }}
 chain forward {{ type filter hook forward priority filter; policy accept;
 ip protocol udp ip saddr != {{ 10.231.1.1, 10.231.2.1 }} ip daddr != {{ 10.231.1.1, 10.231.2.1 }} drop
 }}
}}
"""
            net(router, "nft", "-f", "-", input=rules)
        command("sysctl", "-q", "-w", "net.ipv4.ip_forward=1")

        def launch(name, argv, namespace=None):
            if namespace:
                argv = ["nsenter", "-t", str(spaces[namespace]), "-n", *argv]
            child = subprocess.Popen(argv, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                     bufsize=0)
            children.append(child)
            os.set_blocking(child.stdout.fileno(), False)
            buffers[name] = bytearray()
            output_bytes[name] = 0
            selector.register(child.stdout, selectors.EVENT_READ, name)
            return child

        def read_output():
            lines = []
            for key, _ in selector.select(.1):
                name = key.data
                try:
                    chunk = os.read(key.fileobj.fileno(), 65536)
                except BlockingIOError:
                    continue
                output_bytes[name] += len(chunk)
                if output_bytes[name] > 1024 * 1024:
                    raise RuntimeError(f"{name} exceeded the 1 MiB output limit")
                pending = buffers[name]
                pending.extend(chunk)
                while True:
                    newline = pending.find(b"\n")
                    if newline < 0:
                        break
                    if newline > 65536:
                        raise RuntimeError(f"{name} exceeded the 64 KiB line limit")
                    line = bytes(pending[:newline + 1]).decode("utf-8", errors="replace")
                    del pending[:newline + 1]
                    print(f"[{name}] {line}", end="", flush=True)
                    lines.append((name, line))
                if len(pending) > 65536:
                    raise RuntimeError(f"{name} exceeded the 64 KiB line limit")
                if not chunk:
                    if pending:
                        line = bytes(pending).decode("utf-8", errors="replace")
                        print(f"[{name}] {line}", flush=True)
                        lines.append((name, line))
                        pending.clear()
                    selector.unregister(key.fileobj)
                    key.fileobj.close()
                    closed.add(name)
            return lines

        if args.mode == "carrier":
            server_name = "alice" if args.zig_role == "server" else "bob"
            client_name = "bob" if server_name == "alice" else "alice"
            server_binary = args.zig_peer if server_name == "alice" else args.rust_peer
            client_binary = args.zig_peer if client_name == "alice" else args.rust_peer
            server_expected = args.bob_id if server_name == "alice" else args.alice_id
            client_expected = args.bob_id if client_name == "alice" else args.alice_id
            server = launch(server_name, [server_binary, "--protocol", "relay", "--tls", "iroh",
                "--role", "server", "--bind", "0.0.0.0:3340",
                "--seed-hex", ("5a" if server_name == "alice" else "6c") * 32,
                "--expect-peer", server_expected, "--message", args.message,
                "--for", str(args.timeout * 1000)])
            deadline = time.monotonic() + args.timeout
            relay_ready = False
            registered = False
            while time.monotonic() < deadline:
                for name, line in read_output():
                    if name == server_name:
                        relay_ready |= "relay-ready:" in line
                        registered |= "relay-client-ready: registered" in line
                if server_name in closed or server.poll() is not None:
                    raise RuntimeError("carrier server exited before signed-client readiness")
                if relay_ready and registered:
                    break
            else:
                raise TimeoutError("carrier server readiness")
            index = 1 if client_name == "alice" else 2
            client = launch(client_name, [client_binary, "--protocol", "relay", "--tls", "iroh",
                "--role", "client", "--bind", f"10.232.{index}.2:4444",
                "--seed-hex", ("5a" if client_name == "alice" else "6c") * 32,
                "--expect-peer", client_expected, "--relay-url", f"http://10.231.{index}.1:3340/",
                "--message", args.message, "--for", str(args.timeout * 1000)], client_name)
            roles = {server_name: server, client_name: client}
            expected_ids = {server_name: server_expected, client_name: client_expected}
            payload_hex = args.message.encode().hex()
            proofs = set()
            while time.monotonic() < deadline:
                for name, line in read_output():
                    match = CARRIER.search(line)
                    if match and name in roles:
                        remote, payload = match.groups()
                        if remote != expected_ids[name] or payload != payload_hex:
                            raise RuntimeError(f"{name} carrier identity or application payload mismatch")
                        proofs.add(name)
                for name, child in roles.items():
                    status = child.poll()
                    if status not in (None, 0):
                        raise RuntimeError(f"{name} carrier exited {status}")
                    if name in closed and name not in proofs:
                        raise RuntimeError(f"{name} output ended before carrier proof")
                if (all(name in proofs for name in roles)
                        and all(name in closed and child.poll() == 0
                                for name, child in roles.items())):
                    print("relay-carrier-smoke: PASS (carrier identity and payload only)", flush=True)
                    return 0
            raise TimeoutError("pinned relay carrier exchange")

        relay_argv = [args.rust_peer, "--protocol", "relay", "--tls", "iroh",
            "--role", "server", "--bind", "0.0.0.0:3340", "--seed-hex", "44" * 32,
            "--for", str(args.timeout * 1000)]
        if args.mode == "nat":
            relay_argv.extend(["--relay-qad-bind", "0.0.0.0:3341",
                "--relay-qad-cert", args.qad_cert, "--relay-qad-key", args.qad_key])
        relay = launch("relay", relay_argv)
        deadline = time.monotonic() + args.timeout
        while time.monotonic() < deadline:
            ready = any("relay-ready:" in line for name, line in read_output() if name == "relay")
            if "relay" in closed or relay.poll() is not None:
                raise RuntimeError("relay exited before readiness")
            if ready:
                break
        else:
            raise TimeoutError("relay readiness")
        peers = {}
        for index, name in enumerate(("alice", "bob"), 1):
            zig = (name == "alice")
            role = args.zig_role if zig else ("client" if args.zig_role == "server" else "server")
            binary = args.zig_peer if zig else args.rust_peer
            expected = args.bob_id if zig else args.alice_id
            argv = [binary, "--protocol", "relay-endpoint", "--tls", "iroh", "--role", role,
                "--bind", f"10.232.{index}.2:4444", "--seed-hex", ("5a" if zig else "6c") * 32,
                "--expect-peer", expected, "--relay-url", f"http://10.231.{index}.1:3340/",
                "--message", args.message, "--for", str(args.timeout * 1000)]
            if args.mode == "relay-only":
                argv.append("--relay-only")
            elif zig:
                argv.extend(["--local-candidate", "10.231.1.2:4444"])
                print("candidate-provenance: configured alice 10.231.1.2:4444 "
                      "(not QAD-observed)", flush=True)
            else:
                argv.extend(["--relay-qad-bind", f"10.231.{index}.1:3341",
                    "--relay-qad-cert", args.qad_cert])
            peers[name] = launch(name, argv, name)
        proofs = {}
        opened = False
        payload_bytes = args.message.encode()
        payload_hex = payload_bytes.hex()
        required = "2" if args.mode == "nat" else "1"
        while time.monotonic() < deadline:
            for name, line in read_output():
                match = PHASE.search(line)
                if match and name in peers:
                    phase, stable, remote, route, size, payload = match.groups()
                    expected = args.bob_id if name == "alice" else args.alice_id
                    if remote != expected or int(size) != len(payload_bytes) or payload != payload_hex:
                        raise RuntimeError("peer identity or application payload mismatch")
                    if route != ("relay" if phase == "1" else "direct"):
                        raise RuntimeError("wrong selected path")
                    if phase == "2" and (not opened or proofs.get((name, "1")) != stable):
                        raise RuntimeError("phase2 did not use the same phase1 connection")
                    if (name, phase) in proofs and proofs[(name, phase)] != stable:
                        raise RuntimeError("peer changed the authenticated connection")
                    proofs[(name, phase)] = stable
            if "relay" in closed or relay.poll() is not None:
                raise RuntimeError("relay exited before the exchange completed")
            for name, child in peers.items():
                status = child.poll()
                if status not in (None, 0):
                    raise RuntimeError(f"{name} exited {status}")
                if name in closed and (name, required) not in proofs:
                    raise RuntimeError(f"{name} output ended before phase{required} proof")
            if all((name, "1") in proofs for name in peers):
                if args.mode == "nat" and not opened:
                    for router in ("router-a", "router-b"):
                        net(router, "nft", "flush", "chain", "ip", "relay_smoke", "forward")
                    opened = True
                    print("controller: peer UDP opened after both authenticated relay byte exchanges", flush=True)
                if (all((name, required) in proofs for name in peers)
                        and all(name in closed and child.poll() == 0
                                for name, child in peers.items())):
                    if args.mode == "nat":
                        conntrack = shutil.which("conntrack")
                        if conntrack is None:
                            print("nat-mapping: conntrack unavailable; mapping not inspected", flush=True)
                        else:
                            for index, router in enumerate(("router-a", "router-b"), 1):
                                listing = net(router, conntrack, "-L", "-p", "udp",
                                    "--orig-src", f"10.232.{index}.2", "--orig-port-src", "4444")
                                found = False
                                for line in listing.splitlines():
                                    tuples = re.findall(
                                        r"src=(\S+) dst=(\S+) sport=(\d+) dport=(\d+)", line)
                                    if len(tuples) != 2:
                                        continue
                                    original, reply = tuples
                                    if original[1] != f"10.231.{3 - index}.2":
                                        continue
                                    if reply[1] != f"10.231.{index}.2" or reply[3] != "4444":
                                        raise RuntimeError(f"{router} did not preserve UDP source port 4444")
                                    found = True
                                    print(f"[{router}] nat-mapping: {line}", flush=True)
                                if not found:
                                    raise RuntimeError(f"{router} has no direct UDP masquerade mapping")
                    print("relay-smoke: PASS", flush=True)
                    return 0
        raise TimeoutError("authenticated relay/direct exchange")
    finally:
        selector.close()
        for child in reversed(children):
            if child.poll() is None:
                child.terminate()
            try:
                child.wait(timeout=3)
            except subprocess.TimeoutExpired:
                child.kill()
                child.wait()

class NamespaceSafetyTests(unittest.TestCase):
    """Pure metadata regressions; discovery never enters the network driver."""

    def setUp(self):
        self.baseline = {"net": "net:[100]", "user": "user:[200]", "uid": "1000"}
        self.current = {"net": "net:[101]", "user": "user:[201]"}

    def validate(self, baseline=None, current=None, uid=0, euid=0, uid_map="0 1000 1\n"):
        return validate_namespace_metadata(
            self.baseline if baseline is None else baseline,
            self.current if current is None else current, uid, euid, uid_map)

    def test_separate_namespaces_and_exact_nonroot_mapping(self):
        self.assertIsNone(self.validate())

    def test_missing_outer_baseline_fails_closed(self):
        for key in self.baseline:
            with self.subTest(key=key):
                baseline = self.baseline.copy()
                del baseline[key]
                with self.assertRaisesRegex(RuntimeError, "outer namespace baseline"):
                    self.validate(baseline=baseline)
        with self.assertRaisesRegex(RuntimeError, "outer namespace baseline"):
            self.validate(baseline={})

    def test_malformed_outer_baseline_fails_closed(self):
        for key, value in (("net", "user:[100]"), ("user", ""),
                           ("uid", "0"), ("uid", "-1"), ("uid", "not-a-uid")):
            with self.subTest(key=key, value=value):
                baseline = {**self.baseline, key: value}
                with self.assertRaisesRegex(RuntimeError, "outer namespace baseline"):
                    self.validate(baseline=baseline)

    def test_same_network_namespace_is_rejected(self):
        with self.assertRaisesRegex(RuntimeError, "caller's net namespace"):
            self.validate(current={**self.current, "net": self.baseline["net"]})

    def test_same_user_namespace_is_rejected(self):
        with self.assertRaisesRegex(RuntimeError, "caller's user namespace"):
            self.validate(current={**self.current, "user": self.baseline["user"]})

    def test_wrong_uid_mapping_is_rejected(self):
        for uid_map in ("", "0 0 1\n", "0 1001 1\n", "1 1000 1\n",
                        "0 1000 2\n", "0 1000 1\n1 1001 1\n",
                        "0 1000\n", "not a mapping\n"):
            with self.subTest(uid_map=uid_map):
                with self.assertRaisesRegex(RuntimeError, "private user namespace"):
                    self.validate(uid_map=uid_map)

    def test_nonroot_inner_credentials_are_rejected(self):
        for uid, euid in ((1000, 0), (0, 1000), (1000, 1000)):
            with self.subTest(uid=uid, euid=euid):
                with self.assertRaisesRegex(RuntimeError, "private user namespace"):
                    self.validate(uid=uid, euid=euid)



if __name__ == "__main__":
    sys.exit(main())
